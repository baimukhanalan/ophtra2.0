import { Vector3 } from 'three';
import { LAND_H, LAND_RLE, LAND_W } from './landmask';

export const DEG = Math.PI / 180;
export const EARTH_KM = 6371;

/** Unit-sphere position for latitude/longitude (degrees). */
export function llToVec(lat: number, lng: number, r = 1, out = new Vector3()): Vector3 {
  const phi = (90 - lat) * DEG;
  const theta = (lng + 180) * DEG;
  return out.set(-r * Math.sin(phi) * Math.cos(theta), r * Math.cos(phi), r * Math.sin(phi) * Math.sin(theta));
}

export function vecToLl(v: Vector3): { lat: number; lng: number } {
  const r = v.length() || 1;
  const lat = 90 - Math.acos(Math.max(-1, Math.min(1, v.y / r))) / DEG;
  let lng = Math.atan2(v.z, -v.x) / DEG - 180;
  if (lng < -180) lng += 360;
  return { lat, lng };
}

let landBits: Uint8Array | null = null;
function decodeLand(): Uint8Array {
  if (landBits) return landBits;
  const bits = new Uint8Array(LAND_W * LAND_H);
  const rows = LAND_RLE.split(';');
  for (let y = 0; y < rows.length; y++) {
    const runs = rows[y].split(',');
    let x = 0;
    let v = 0;
    for (const r of runs) {
      const n = +r;
      if (v) bits.fill(1, y * LAND_W + x, y * LAND_W + x + n);
      x += n;
      v ^= 1;
    }
  }
  landBits = bits;
  return bits;
}

export function isLand(lat: number, lng: number): boolean {
  const bits = decodeLand();
  const x = Math.min(LAND_W - 1, Math.max(0, Math.floor(((lng + 180) / 360) * LAND_W)));
  const y = Math.min(LAND_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * LAND_H)));
  return bits[y * LAND_W + x] === 1;
}

